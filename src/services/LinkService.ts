import * as fs from 'fs';
import * as path from 'path';
import { createHash } from 'crypto';
import { App, FileSystemAdapter, Notice } from 'obsidian';

// 外掛產生的核心檔都帶有此標記，用來分辨「外掛的檔案」與「使用者的檔案」
export const GENERATED_MARKER = 'Generated by Agent Terminal.';
// 改名前 (Intellect Terminal) 的標記：舊版留下的檔案仍視為外掛的
const LEGACY_GENERATED_MARKERS = ['Generated by Intellect Terminal.'];

/** Bootstrap 會取代的檔案 (先在確認視窗列出)：yours = 使用者自己的檔案，改名為 .bak；edited = 外掛產生後被編輯過，複製為 .bak */
export interface BootstrapChange {
    path: string; // 相對於 vault
    reason: 'yours' | 'edited';
}

type LinkAction = 'create' | 'keep' | 'relink' | 'replace' | 'kept' | 'backup';

export class LinkService {
    private static readonly CORE_FILE = 'ai-core.md';
    private static readonly CORE_DIR = '.ai-core';
    // 改名前使用的核心檔與資料夾，bootstrap 時遷移到新名稱
    private static readonly LEGACY_CORE_FILE = 'intellect.md';
    private static readonly LEGACY_CORE_DIR = '.intellect';
    private static readonly SKILLS_DIR = 'skills';
    // 上次寫入 ai-core.md 內容的 SHA-256，用來分辨「外掛產生後未動過」與「之後被編輯過」
    private static readonly CORE_FINGERPRINT_FILE = 'ai-core.md.sha256';
    // 各 skill 上次寫入的 SKILL.md 指紋 ({ 名稱: SHA-256 })，用來分辨 skill 是否被編輯過
    private static readonly SKILL_FINGERPRINTS_FILE = 'skill-fingerprints.json';

    // 各 AI 工具讀取的指示檔 (使用官方檔名；Linux 檔案系統區分大小寫)
    private static readonly ALIAS_FILES = [
        'CLAUDE.md',      // Claude Code
        'GEMINI.md',      // Antigravity CLI (agy)
        'AGENTS.md',      // agy、Codex 等通用慣例
        '.cursorrules',
        '.windsurfrules'
    ];
    // 舊版建立、現已不使用的別名，遷移時移除 (僅限外掛自己建立的連結/未編輯的複本)：
    // 小寫的 gemini.md / agents.md，以及沒有任何工具會讀的 CODEGEN.md
    private static readonly LEGACY_ALIAS_FILES = ['gemini.md', 'agents.md', 'CODEGEN.md'];

    // 讀取工作區 skills 的 AI 工具：Claude Code (.claude/skills)、agy (.agents/skills)
    private static readonly SKILL_TOOL_DIRS = ['.claude', '.agents'];
    // 舊版連結過、現已無工具讀取的 skills 位置 (Gemini CLI 已由 agy 取代)
    private static readonly LEGACY_SKILL_TOOL_DIRS = ['.gemini'];
    private static readonly SKILL_FILE = 'SKILL.md';

    /**
     * @param skills skill 名稱 → SKILL.md 內容；寫成 .ai-core/skills/<名稱>/SKILL.md
     */
    /**
     * 不做任何變更，回傳 bootstrap 會取代 (備份成 .bak) 的檔案，供確認視窗列出。
     * 與 bootstrapUnifiedCore 使用同一組判斷 (coreAction / isSkillEdited / dirNeedsBackup / linkAction)；
     * 舊版結構遷移時會移除的項目 (外掛自己建立的) 不列入。
     */
    static prepareBootstrap(app: App, mainContent: string, skills: Record<string, string>): BootstrapChange[] {
        if (!(app.vault.adapter instanceof FileSystemAdapter)) return [];
        const basePath = app.vault.adapter.getBasePath();
        const layout = this.layout(basePath);
        const changes: BootstrapChange[] = [];
        const add = (absPath: string, reason: BootstrapChange['reason']) =>
            changes.push({ path: path.relative(basePath, absPath), reason });
        const removedByMigration = this.migrationRemovals(basePath, layout.coreSkillsPath);

        // skills
        const recorded = this.readSkillFingerprints(layout.skillFingerprintsPath);
        for (const [name, content] of Object.entries(skills)) {
            const skillDir = path.join(layout.coreSkillsPath, name);
            if (this.dirNeedsBackup(skillDir)) {
                add(skillDir, 'yours');
                continue;
            }
            const skillFile = path.join(skillDir, this.SKILL_FILE);
            if (this.isSkillEdited(skillFile, content, recorded[name])) add(skillFile, 'edited');
        }

        // ai-core.md (舊版的 intellect.md 會先改名成 ai-core.md)
        const legacyCore = this.generatedLegacyCore(basePath);
        const currentCore = this.pathExists(layout.coreAbsPath) ? layout.coreAbsPath : legacyCore;
        if (currentCore) {
            const action = this.coreAction(currentCore, layout.fingerprintPath, mainContent);
            if (action === 'backup') add(layout.coreAbsPath, 'yours');
            if (action === 'backupByCopy') add(layout.coreAbsPath, 'edited');
        }

        // 根目錄的指示檔
        const isKnownCoreContent = this.knownCoreContent(layout.coreAbsPath, layout.fingerprintPath, mainContent);
        for (const alias of this.ALIAS_FILES) {
            const aliasAbsPath = path.join(basePath, alias);
            if (removedByMigration(aliasAbsPath)) continue;
            if (this.linkAction(layout.coreAbsPath, aliasAbsPath, 'file', isKnownCoreContent) === 'backup') add(aliasAbsPath, 'yours');
        }

        // 各工具的 skills 資料夾
        const entries = this.coreSkillEntries(basePath, layout.coreSkillsPath, Object.keys(skills));
        for (const tool of this.SKILL_TOOL_DIRS) {
            const toolSkillsDir = path.join(basePath, tool, this.SKILLS_DIR);
            if (removedByMigration(toolSkillsDir)) continue;
            if (this.dirNeedsBackup(toolSkillsDir)) {
                add(toolSkillsDir, 'yours');
                continue;
            }
            for (const [name, type] of entries) {
                const link = path.join(toolSkillsDir, name);
                if (removedByMigration(link)) continue;
                if (this.linkAction(path.join(layout.coreSkillsPath, name), link, type) === 'backup') add(link, 'yours');
            }
        }
        return changes;
    }

    /**
     * @param skills skill 名稱 → SKILL.md 內容；寫成 .ai-core/skills/<名稱>/SKILL.md
     */
    static bootstrapUnifiedCore(
        app: App,
        mainContent: string,
        skills: Record<string, string>
    ): void {
        if (!(app.vault.adapter instanceof FileSystemAdapter)) {
            new Notice('Bootstrapping the AI core needs direct file system access, which is only available in the desktop app.');
            return;
        }

        const basePath = app.vault.adapter.getBasePath();
        const { coreAbsPath, coreSkillsPath, fingerprintPath, skillFingerprintsPath } = this.layout(basePath);

        try {
            // 覆寫前先把不屬於外掛的檔案/資料夾備份成 .bak，記錄下來通知使用者
            const backups: string[] = [];
            const record = (original: string, backup: string | null) => {
                if (backup) backups.push(`${path.relative(basePath, original)} → ${path.relative(basePath, backup)}`);
            };
            // 不分大小寫的檔案系統上，與別名只差大小寫的使用者檔案 (例如 gemini.md 之於 GEMINI.md) 保留不動
            const kept: string[] = [];
            const onKept = (existing: string, alias: string) => {
                kept.push(`${path.relative(basePath, existing)} (same name as ${path.relative(basePath, alias)} on this file system, not linked)`);
            };

            // 1. 遷移改名前的核心檔/資料夾，確保實體資料夾存在，並遷移舊版 skills 結構
            this.migrateLegacyCore(basePath, coreAbsPath, coreSkillsPath);
            fs.mkdirSync(coreSkillsPath, { recursive: true });
            this.migrateLegacySkills(basePath, coreSkillsPath, Object.keys(skills));

            // 2. 寫入 skills：每個 skill 一個資料夾 + SKILL.md (Claude Code 與 agy 共同的格式)。
            //    外掛產生後被編輯過的 SKILL.md 先複製成 .bak；記下指紋供下次判斷
            const recorded = this.readSkillFingerprints(skillFingerprintsPath);
            const fingerprints: Record<string, string> = {};
            for (const [name, content] of Object.entries(skills)) {
                const skillDir = path.join(coreSkillsPath, name);
                record(skillDir, this.ensureRealDir(skillDir));
                const skillFile = path.join(skillDir, this.SKILL_FILE);
                if (this.isSkillEdited(skillFile, content, recorded[name])) record(skillFile, this.backupByCopy(skillFile));
                fs.writeFileSync(skillFile, content, 'utf8');
                fingerprints[name] = this.fingerprint(content);
            }
            fs.writeFileSync(skillFingerprintsPath, JSON.stringify(fingerprints), 'utf8');

            // 連結失敗時留下的複本，內容是「上次產生的」或「這次要寫入的」核心內容才能直接刪除，其餘先備份
            const isKnownCoreContent = this.knownCoreContent(coreAbsPath, fingerprintPath, mainContent);
            const coreAction = this.coreAction(coreAbsPath, fingerprintPath, mainContent);
            if (coreAction === 'backup') record(coreAbsPath, this.backup(coreAbsPath));
            // 外掛產生的檔案在產生後被改過 (例如 explore-vault 寫回的 Directory Definitions)：
            // 以複製備份，原檔 inode 不變，既有的硬連結仍會跟著更新
            if (coreAction === 'backupByCopy') record(coreAbsPath, this.backupByCopy(coreAbsPath));
            // 原地覆寫內容 (保留 inode)，既有的硬連結會跟著更新；記下指紋供下次判斷是否被編輯過
            fs.writeFileSync(coreAbsPath, mainContent, 'utf8');
            fs.writeFileSync(fingerprintPath, this.fingerprint(mainContent), 'utf8');

            // 3. 建立根目錄別名連結 (先移除舊版的小寫別名)
            this.removeLegacyAliases(basePath, coreAbsPath, isKnownCoreContent);
            for (const alias of this.ALIAS_FILES) {
                const aliasAbsPath = path.join(basePath, alias);
                record(aliasAbsPath, this.ensureLink(coreAbsPath, aliasAbsPath, 'file', { isKnownCopy: isKnownCoreContent, onKept }));
            }

            // 4. 在各工具的 skills 資料夾內，為 .ai-core/skills 的每個項目建立連結。
            //    不取代整個資料夾，使用者原有的 skills 可以並存；使用者放進 .ai-core/skills 的也會一併連結
            for (const tool of this.SKILL_TOOL_DIRS) {
                const toolSkillsDir = path.join(basePath, tool, this.SKILLS_DIR);
                record(toolSkillsDir, this.ensureRealDir(toolSkillsDir));
                for (const entry of fs.readdirSync(coreSkillsPath, { withFileTypes: true })) {
                    const target = path.join(coreSkillsPath, entry.name);
                    const link = path.join(toolSkillsDir, entry.name);
                    record(link, this.ensureLink(target, link, entry.isDirectory() ? 'dir' : 'file', { onKept }));
                }
            }

            let message = '✅ AI core initialized and synced.';
            if (backups.length > 0) message += ` Existing files were backed up: ${backups.join(', ')}`;
            if (kept.length > 0) message += ` Kept your files: ${kept.join(', ')}`;
            new Notice(message);
        } catch (error) {
            console.error('[AgentTerminal] Bootstrap failed:', error);
            new Notice('❌ Initialization failed: ' + (error as Error).message);
        }
    }

    private static layout(basePath: string) {
        const coreDir = path.join(basePath, this.CORE_DIR);
        return {
            coreAbsPath: path.join(basePath, this.CORE_FILE),
            coreSkillsPath: path.join(coreDir, this.SKILLS_DIR),
            fingerprintPath: path.join(coreDir, this.CORE_FINGERPRINT_FILE),
            skillFingerprintsPath: path.join(coreDir, this.SKILL_FINGERPRINTS_FILE)
        };
    }

    /** 可直接刪除、不需備份的核心內容：這次要寫入的、目前的，或與上次指紋相符的 */
    private static knownCoreContent(coreAbsPath: string, fingerprintPath: string, mainContent: string): (content: string) => boolean {
        const previousCore = this.readOrNull(coreAbsPath);
        const previousFingerprint = this.readOrNull(fingerprintPath)?.trim();
        return (content: string) => content === mainContent
            || content === previousCore
            || (!!previousFingerprint && this.fingerprint(content) === previousFingerprint);
    }

    /** ai-core.md 的處理：使用者自己的檔案改名備份；外掛產生後被編輯過的複製備份 */
    private static coreAction(corePath: string, fingerprintPath: string, mainContent: string): 'none' | 'backup' | 'backupByCopy' {
        if (!this.pathExists(corePath)) return 'none';
        if (!this.hasGeneratedMarker(corePath)) return 'backup';
        return this.isEditedSinceGenerated(corePath, fingerprintPath, mainContent) ? 'backupByCopy' : 'none';
    }

    /**
     * 外掛的 SKILL.md 是否在產生後被編輯過 (需先備份)。
     * 沒有記錄指紋 (先前的版本) 時無從分辨「被編輯過」與「舊版內容」，視為未編輯，照舊直接更新。
     */
    private static isSkillEdited(skillFile: string, newContent: string, recordedFingerprint: string | undefined): boolean {
        const content = this.readOrNull(skillFile);
        if (content === null || content === newContent || !recordedFingerprint) return false;
        return recordedFingerprint !== this.fingerprint(content);
    }

    private static readSkillFingerprints(p: string): Record<string, string> {
        try {
            const data = JSON.parse(fs.readFileSync(p, 'utf8')) as unknown;
            if (typeof data !== 'object' || data === null) return {};
            return Object.fromEntries(Object.entries(data).filter((entry): entry is [string, string] => typeof entry[1] === 'string'));
        } catch {
            return {};
        }
    }

    /** 改名前留下、含產生標記的 intellect.md (遷移時會改名為 ai-core.md 或刪除) */
    private static generatedLegacyCore(basePath: string): string | null {
        const legacyCore = path.join(basePath, this.LEGACY_CORE_FILE);
        return this.pathExists(legacyCore) && fs.lstatSync(legacyCore).isFile() && this.hasGeneratedMarker(legacyCore)
            ? legacyCore : null;
    }

    /** 各工具 skills 資料夾要連結的項目：.ai-core/skills (尚未建立時為遷移前的 .intellect/skills) 的內容，加上這次要寫入的 skills */
    private static coreSkillEntries(basePath: string, coreSkillsPath: string, skillNames: string[]): Map<string, 'file' | 'dir'> {
        const entries = new Map<string, 'file' | 'dir'>();
        const legacySkills = path.join(basePath, this.LEGACY_CORE_DIR, this.SKILLS_DIR);
        const source = this.pathExists(path.dirname(coreSkillsPath)) ? coreSkillsPath : legacySkills;
        try {
            for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
                entries.set(entry.name, entry.isDirectory() ? 'dir' : 'file');
            }
        } catch { /* 還沒有任何 skill */ }
        for (const name of skillNames) entries.set(name, 'dir');
        return entries;
    }

    /**
     * 遷移舊版結構時會移除的項目 (都是外掛自己建立的，不需備份)：
     * 指向舊核心檔的別名、指向舊 skills 資料夾的連結、整個 skills 資料夾的連結 (見 migrateLegacyCore / migrateLegacySkills)
     */
    private static migrationRemovals(basePath: string, coreSkillsPath: string): (p: string) => boolean {
        const legacyCore = this.generatedLegacyCore(basePath);
        const legacyContent = legacyCore ? this.readOrNull(legacyCore) : null;
        const legacySkillsReal = this.realpathOrNull(path.join(basePath, this.LEGACY_CORE_DIR, this.SKILLS_DIR));
        const coreSkillsReal = this.realpathOrNull(coreSkillsPath);
        return (p: string) => {
            if (!this.pathExists(p)) return false;
            if (legacyCore && path.dirname(p) === basePath
                && this.isDisposable(legacyCore, p, content => content === legacyContent)) return true;
            if (!fs.lstatSync(p).isSymbolicLink()) return false;
            const real = this.realpathOrNull(p);
            if (real === null) return false;
            if (legacySkillsReal && (real === legacySkillsReal || path.dirname(real) === legacySkillsReal)) return true;
            return real === coreSkillsReal && path.basename(p) === this.SKILLS_DIR;
        };
    }

    /**
     * Checks if a path exists, including broken symlinks/junctions
     * (fs.existsSync returns false for broken symlinks, lstatSync does not)
     */
    private static pathExists(p: string): boolean {
        try {
            fs.lstatSync(p);
            return true;
        } catch {
            return false;
        }
    }

    /**
     * 遷移改名前 (Intellect Terminal) 的 intellect.md 與 .intellect (只動外掛自己建立的項目)：
     * - 先移除指向舊核心檔/舊 skills 的連結與複本，否則改名後會變成斷掉的連結而被當成使用者的檔案備份
     * - 舊核心檔 (含產生標記) 改名為新核心檔；新核心檔已存在時直接刪除舊檔
     * - 新資料夾不存在時，整個 .intellect 改名為 .ai-core (使用者放進去的 skills 一併搬移)
     * 使用者自己的 intellect.md (沒有產生標記) 與無關的 .intellect 資料夾維持不動。
     */
    private static migrateLegacyCore(basePath: string, coreAbsPath: string, coreSkillsPath: string): void {
        const legacyCore = path.join(basePath, this.LEGACY_CORE_FILE);
        if (this.pathExists(legacyCore) && fs.lstatSync(legacyCore).isFile() && this.hasGeneratedMarker(legacyCore)) {
            const legacyContent = this.readOrNull(legacyCore);
            for (const alias of [...this.ALIAS_FILES, ...this.LEGACY_ALIAS_FILES]) {
                const aliasPath = path.join(basePath, alias);
                // 被編輯過的複本留著，之後由 ensureLink 備份
                if (this.pathExists(aliasPath)
                    && this.isDisposable(legacyCore, aliasPath, content => content === legacyContent)) {
                    fs.unlinkSync(aliasPath);
                }
            }
            if (this.pathExists(coreAbsPath)) fs.unlinkSync(legacyCore);
            else fs.renameSync(legacyCore, coreAbsPath);
        }

        const legacySkills = path.join(basePath, this.LEGACY_CORE_DIR, this.SKILLS_DIR);
        if (!this.pathExists(legacySkills) || !fs.lstatSync(legacySkills).isDirectory()) return;
        const legacySkillsReal = fs.realpathSync(legacySkills);
        for (const tool of [...this.SKILL_TOOL_DIRS, ...this.LEGACY_SKILL_TOOL_DIRS]) {
            const toolSkillsDir = path.join(basePath, tool, this.SKILLS_DIR);
            if (!this.pathExists(toolSkillsDir)) continue;
            if (fs.lstatSync(toolSkillsDir).isSymbolicLink()) {
                // 舊版「整個資料夾」的連結
                if (this.realpathOrNull(toolSkillsDir) === legacySkillsReal) this.removeLink(toolSkillsDir);
                continue;
            }
            for (const entry of fs.readdirSync(toolSkillsDir)) {
                const link = path.join(toolSkillsDir, entry);
                if (!fs.lstatSync(link).isSymbolicLink()) continue;
                const real = this.realpathOrNull(link);
                if (real !== null && path.dirname(real) === legacySkillsReal) this.removeLink(link);
            }
        }

        const coreDir = path.dirname(coreSkillsPath);
        if (!this.pathExists(coreDir)) fs.renameSync(path.join(basePath, this.LEGACY_CORE_DIR), coreDir);
    }

    private static realpathOrNull(p: string): string | null {
        try {
            return fs.realpathSync(p);
        } catch {
            return null;
        }
    }

    /**
     * 遷移舊版結構 (只動外掛自己建立的項目)：
     * - 各工具「整個 skills 資料夾」連到 .ai-core/skills 的連結 → 移除，之後改為逐個 skill 連結
     * - .gemini 底下只剩空資料夾時一併移除 (agy 不讀 .gemini/skills)
     * - 舊版平鋪的 <名稱>.md skill 檔 (frontmatter name 相符才視為外掛的) → 刪除，改用資料夾格式
     */
    private static migrateLegacySkills(basePath: string, coreSkillsPath: string, skillNames: string[]): void {
        for (const tool of [...this.SKILL_TOOL_DIRS, ...this.LEGACY_SKILL_TOOL_DIRS]) {
            const toolSkillsDir = path.join(basePath, tool, this.SKILLS_DIR);
            if (this.pathExists(toolSkillsDir)
                && fs.lstatSync(toolSkillsDir).isSymbolicLink()
                && this.classifyEntry(coreSkillsPath, toolSkillsDir, 'dir') === 'linked') {
                this.removeLink(toolSkillsDir);
            }
        }

        for (const tool of this.LEGACY_SKILL_TOOL_DIRS) {
            const toolDir = path.join(basePath, tool);
            try {
                if (fs.readdirSync(toolDir).length === 0) fs.rmdirSync(toolDir);
            } catch { /* 不存在或無法讀取 */ }
        }

        for (const name of skillNames) {
            const legacyFile = path.join(coreSkillsPath, `${name}.md`);
            try {
                const content = fs.readFileSync(legacyFile, 'utf8');
                if (new RegExp(`^---\\s*\\nname:\\s*${name}\\s*\\n`).test(content)) fs.unlinkSync(legacyFile);
            } catch { /* 不存在 */ }
        }
    }

    /**
     * 移除舊版建立、現已不使用的別名 (gemini.md、agents.md、CODEGEN.md)。
     * 以 readdir 比對實際的檔名大小寫：在不分大小寫的檔案系統上，gemini.md 與 GEMINI.md 是同一個項目。
     */
    private static removeLegacyAliases(
        basePath: string,
        coreAbsPath: string,
        isKnownCoreContent: (content: string) => boolean
    ): void {
        const entries = fs.readdirSync(basePath);
        for (const legacy of this.LEGACY_ALIAS_FILES) {
            if (!entries.includes(legacy)) continue;
            const legacyPath = path.join(basePath, legacy);
            if (this.isDisposable(coreAbsPath, legacyPath, isKnownCoreContent)) fs.unlinkSync(legacyPath);
        }
    }

    /**
     * 外掛建立的檔案別名是否可以直接刪除 (不需備份)：指向 target 的連結，
     * 或內容未被編輯過 (isKnownContent) 的複本
     */
    private static isDisposable(
        targetAbsPath: string,
        aliasAbsPath: string,
        isKnownContent: (content: string) => boolean
    ): boolean {
        const kind = this.classifyEntry(targetAbsPath, aliasAbsPath, 'file');
        if (kind === 'linked') return true;
        if (kind === 'foreign') return false;
        const content = this.readOrNull(aliasAbsPath);
        return content !== null && isKnownContent(content);
    }

    /** 確保是實體資料夾 (或指向資料夾的連結)；若是同名檔案，先備份。回傳備份路徑 */
    private static ensureRealDir(dir: string): string | null {
        if (this.pathExists(dir) && !this.dirNeedsBackup(dir)) return null;
        const backupPath = this.pathExists(dir) ? this.backup(dir) : null;
        fs.mkdirSync(dir, { recursive: true });
        return backupPath;
    }

    /** 同名的是檔案或斷掉的連結 (不是資料夾，也不是指向資料夾的連結)：建立資料夾前要先備份 */
    private static dirNeedsBackup(dir: string): boolean {
        if (!this.pathExists(dir)) return false;
        try {
            return !fs.statSync(dir).isDirectory();
        } catch {
            return true; // 斷掉的連結
        }
    }

    /**
     * 回傳實際佔用 p 這個名稱的項目路徑 (保留磁碟上的大小寫)。
     * 區分大小寫的檔案系統上就是 p 本身；不分大小寫時可能是 gemini.md 之於 GEMINI.md。
     */
    private static actualEntryPath(p: string): string {
        const name = path.basename(p);
        let entries: string[];
        try {
            entries = fs.readdirSync(path.dirname(p));
        } catch {
            return p;
        }
        if (entries.includes(name)) return p;
        const variant = entries.find(entry => entry.toLowerCase() === name.toLowerCase());
        return variant ? path.join(path.dirname(p), variant) : p;
    }

    /** 移除 symlink / junction (POSIX 用 unlink；Windows 的目錄連結需要 rmdir) */
    private static removeLink(p: string): void {
        try {
            fs.unlinkSync(p);
        } catch {
            fs.rmdirSync(p);
        }
    }

    private static hasGeneratedMarker(p: string): boolean {
        try {
            const content = fs.readFileSync(p, 'utf8');
            return [GENERATED_MARKER, ...LEGACY_GENERATED_MARKERS].some(marker => content.includes(marker));
        } catch {
            return false;
        }
    }

    /**
     * 判斷既有的 alias 是否由外掛建立：
     * - linked：已是指向 target 的連結 (symlink/junction，或同 inode 的硬連結)，不需處理
     * - copy：連結失敗時留下的複本 (含產生標記)；內容未被編輯過才可直接覆寫 (見 isDisposable / ensureLink)
     * - foreign：使用者自己的檔案/資料夾，覆寫前必須備份
     */
    private static classifyEntry(targetAbsPath: string, aliasAbsPath: string, type: 'file' | 'dir'): 'linked' | 'copy' | 'foreign' {
        try {
            if (fs.realpathSync(aliasAbsPath) === fs.realpathSync(targetAbsPath)) return 'linked';
        } catch {
            // 斷掉的連結：realpath 失敗，視為 foreign
        }

        if (type === 'file') {
            try {
                const aliasStat = fs.statSync(aliasAbsPath, { bigint: true });
                const targetStat = fs.statSync(targetAbsPath, { bigint: true });
                if (aliasStat.dev === targetStat.dev && aliasStat.ino === targetStat.ino) return 'linked';
            } catch {
                return 'foreign';
            }
            const isRegularFile = fs.lstatSync(aliasAbsPath).isFile();
            if (isRegularFile && this.hasGeneratedMarker(aliasAbsPath)) return 'copy';
        }

        return 'foreign';
    }

    private static isAbsoluteSymlink(p: string): boolean {
        try {
            return fs.lstatSync(p).isSymbolicLink() && path.isAbsolute(fs.readlinkSync(p));
        } catch {
            return false;
        }
    }

    private static fingerprint(content: string): string {
        return createHash('sha256').update(content, 'utf8').digest('hex');
    }

    private static readOrNull(p: string): string | null {
        try {
            return fs.readFileSync(p, 'utf8');
        } catch {
            return null;
        }
    }

    /**
     * 含產生標記的 ai-core.md 是否在外掛產生後被編輯過 (需要先備份)：
     * - 有指紋：內容與上次寫入的指紋不同即視為被編輯過
     * - 沒有指紋 (舊版外掛產生)：無從得知，內容與這次要寫入的不同就備份 (寧可多備份一次)
     */
    private static isEditedSinceGenerated(coreAbsPath: string, fingerprintPath: string, newContent: string): boolean {
        const content = this.readOrNull(coreAbsPath);
        if (content === null || content === newContent) return false;
        const recorded = this.readOrNull(fingerprintPath)?.trim();
        return recorded ? recorded !== this.fingerprint(content) : true;
    }

    /** 下一個可用的備份路徑 (.bak，已存在則用 .bak.1、.bak.2…)，絕不覆寫舊備份 */
    private static nextBackupPath(p: string): string {
        let backupPath = `${p}.bak`;
        for (let i = 1; this.pathExists(backupPath); i++) {
            backupPath = `${p}.bak.${i}`;
        }
        return backupPath;
    }

    /**
     * 將既有項目改名為 .bak (已存在則用 .bak.1、.bak.2…)，絕不覆寫舊備份
     */
    private static backup(p: string): string {
        const backupPath = this.nextBackupPath(p);
        fs.renameSync(p, backupPath);
        return backupPath;
    }

    /** 以複製方式備份檔案：原檔 (與指向它的硬連結) 保持不變，之後原地覆寫 */
    private static backupByCopy(p: string): string {
        const backupPath = this.nextBackupPath(p);
        fs.copyFileSync(p, backupPath, fs.constants.COPYFILE_EXCL);
        return backupPath;
    }

    /**
     * 確保 alias 指向 target。若 alias 是使用者自己的項目，或是被編輯過的複本 (isKnownCopy 不認得其內容)，
     * 先備份；回傳備份路徑 (沒有備份則為 null)
     */
    /**
     * 決定如何讓 alias 指向 target (bootstrap 與確認前的預覽共用)：
     * - create：不存在，直接建立
     * - keep：已是指向 target 的連結
     * - relink：舊版以絕對路徑建立、指向 target 的 symlink，換成相對路徑 (不需備份)
     * - replace：外掛留下且未被編輯的複本 (isKnownCopy 認得其內容)，直接取代
     * - kept：不分大小寫的檔案系統上只差大小寫的使用者項目，保留不動、不建立此別名
     * - backup：使用者自己的項目或被編輯過的複本，先備份
     */
    private static linkAction(
        targetAbsPath: string,
        aliasAbsPath: string,
        type: 'file' | 'dir',
        isKnownCopy?: (content: string) => boolean
    ): LinkAction {
        if (!this.pathExists(aliasAbsPath)) return 'create';
        const existing = this.actualEntryPath(aliasAbsPath);
        const kind = this.classifyEntry(targetAbsPath, existing, type);
        if (kind === 'linked') {
            const isAbsoluteLink = process.platform !== 'win32' && existing === aliasAbsPath && this.isAbsoluteSymlink(existing);
            return isAbsoluteLink ? 'relink' : 'keep';
        }
        const content = kind === 'copy' ? this.readOrNull(existing) : null;
        if (content !== null && isKnownCopy?.(content)) return 'replace';
        return existing !== aliasAbsPath ? 'kept' : 'backup';
    }

    /**
     * 確保 alias 指向 target。若 alias 是使用者自己的項目，或是被編輯過的複本 (isKnownCopy 不認得其內容)，
     * 先備份；回傳備份路徑 (沒有備份則為 null)
     */
    private static ensureLink(
        targetAbsPath: string,
        aliasAbsPath: string,
        type: 'file' | 'dir',
        options: {
            isKnownCopy?: (content: string) => boolean;
            /** 保留了只差大小寫的既有項目 (未建立此別名) 時呼叫 */
            onKept?: (existing: string, alias: string) => void;
        } = {}
    ): string | null {
        const action = this.linkAction(targetAbsPath, aliasAbsPath, type, options.isKnownCopy);
        if (action === 'keep') return null;
        if (action === 'kept') {
            // 例如使用者自己的 gemini.md：在區分大小寫的系統上它與 GEMINI.md 無關，不應被改名或取代；
            // 這裡兩者無法並存，保留使用者的檔案、不建立此別名
            options.onKept?.(this.actualEntryPath(aliasAbsPath), aliasAbsPath);
            return null;
        }

        let backupPath: string | null = null;
        try {
            if (action === 'relink' || action === 'replace') fs.unlinkSync(this.actualEntryPath(aliasAbsPath));
            if (action === 'backup') backupPath = this.backup(aliasAbsPath);
        } catch (e) {
            // 無法備份時寧可跳過，也不刪除使用者的資料
            console.warn(`[AgentTerminal] Failed to back up entry (skipping): ${aliasAbsPath}`, e);
            return null;
        }

        try {
            if (process.platform === 'win32') {
                if (type === 'file') {
                    fs.linkSync(targetAbsPath, aliasAbsPath);
                } else {
                    fs.symlinkSync(targetAbsPath, aliasAbsPath, 'junction');
                }
            } else {
                // 相對路徑：vault 搬移或用 git、Syncthing 同步到路徑不同的電腦後，連結仍然有效
                // (Windows 的硬連結不含路徑；junction 只接受絕對路徑)。
                // 以實際路徑計算：所在資料夾本身是連結 (例如 .claude/skills 連到 vault 外) 時，
                // 相對路徑是從連結實際所在的位置解析
                const linkDir = fs.realpathSync(path.dirname(aliasAbsPath));
                const relativeTarget = path.relative(linkDir, fs.realpathSync(targetAbsPath));
                fs.symlinkSync(relativeTarget, aliasAbsPath, type === 'dir' ? 'dir' : 'file');
            }
        } catch (linkError) {
            console.error(`[AgentTerminal] Linking failed: ${aliasAbsPath}`, linkError);
            if (type === 'file') fs.copyFileSync(targetAbsPath, aliasAbsPath);
        }

        return backupPath;
    }
}
