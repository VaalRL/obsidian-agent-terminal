import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import { builtinModules } from "node:module";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

const commonConfig = {
  bundle: true,
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  external: [
    "obsidian",
    "electron",
    "node-pty",
    ...builtinModules,
    ...builtinModules.map((name) => `node:${name}`)
  ],
};

// 社群外掛商店只會安裝 main.js/manifest.json/styles.css，
// 所以 bridge.ts 先打包成字串，再以 virtual:bridge-source 模組內嵌進 main.js，執行時由外掛寫出 bridge.js
let bridgeSource = "";

const bridgeSourcePlugin = {
  name: "bridge-source",
  setup(build) {
    build.onResolve({ filter: /^virtual:bridge-source$/ }, (args) => ({ path: args.path, namespace: "bridge-source" }));
    build.onLoad({ filter: /.*/, namespace: "bridge-source" }, () => ({
      contents: `export default ${JSON.stringify(bridgeSource)};`,
      loader: "js",
    }));
  },
};

// node-pty 下載清單 (由 scripts/package-native.mjs 產生)：只有正式建置且已打包原生檔時才內嵌，
// 否則為 null —— 外掛不自動下載，開發者自行在外掛資料夾 npm install node-pty
const nativeManifestPath = "dist/native/native-manifest.json";
const nativeManifest = prod && fs.existsSync(nativeManifestPath)
  ? JSON.parse(fs.readFileSync(nativeManifestPath, "utf8"))
  : null;
if (prod) {
  console.log(nativeManifest
    ? `[build] embedding native manifest: ${Object.keys(nativeManifest.assets).join(", ")}`
    : "[build] no native manifest: automatic node-pty download disabled");
}

const nativeManifestPlugin = {
  name: "native-manifest",
  setup(build) {
    build.onResolve({ filter: /^virtual:native-manifest$/ }, (args) => ({ path: args.path, namespace: "native-manifest" }));
    build.onLoad({ filter: /.*/, namespace: "native-manifest" }, () => ({
      contents: `export default ${JSON.stringify(nativeManifest)};`,
      loader: "js",
    }));
  },
};

const pluginContext = await esbuild.context({
  ...commonConfig,
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  plugins: [bridgeSourcePlugin, nativeManifestPlugin],
});

const bridgeContext = await esbuild.context({
  ...commonConfig,
  entryPoints: ["src/services/bridge.ts"],
  sourcemap: false,
  write: false,
  outfile: "bridge.js",
  plugins: [{
    name: "bridge-to-plugin",
    setup(build) {
      // bridge 每次重建後更新內嵌字串；watch 模式下連帶重建 main.js
      build.onEnd(async (result) => {
        if (result.errors.length > 0 || !result.outputFiles) return;
        bridgeSource = result.outputFiles[0].text;
        if (!prod) await pluginContext.rebuild().catch(() => {});
      });
    },
  }],
});

if (prod) {
  await bridgeContext.rebuild();
  await pluginContext.rebuild();
  process.exit(0);
} else {
  await bridgeContext.watch();
  await pluginContext.watch();
}
